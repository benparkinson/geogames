-- What the stats need to know about a game when one of its rounds is answered.
-- Nullable: games created before this migration (at most 24 h old when it runs) have neither,
-- and their rounds are simply not recorded.
alter table game_entity add column play_id uuid;
alter table game_entity add column game_mode varchar(40);

-- One anonymous row per answered round. No foreign keys: rows outlive the games.
create table round_result (
    id             bigint generated by default as identity primary key,
    answered_on    date         not null, -- UTC date only, never a timestamp
    play_id        uuid         not null, -- random per game; links rounds of one game, nothing else
    game_mode      varchar(40)  not null, -- what was requested: a GameType name, or RANDOM
    rounds_in_game smallint     not null,
    round_number   smallint     not null, -- from 0, as in the API
    game_type      varchar(40)  not null, -- this round's GameType
    round_key      varchar(255) not null, -- GameData.roundKey(), e.g. river:Q3392, country:France
    answer_state   varchar(20)  not null, -- CORRECT, GAVE_UP or OUT_OF_GUESSES
    hints_used     smallint     not null,
    wrong_guesses  smallint,              -- as counted against the guess limit; NULL = client didn't report it
    hint_count     smallint     not null, -- the type's hintCount at the time
    guess_limit    smallint     not null, -- the type's guessLimit at the time
    points         smallint     not null  -- Scoring.roundPoints at the time
);
