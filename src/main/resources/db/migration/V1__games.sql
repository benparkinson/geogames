-- Games and their rounds. Written to run on both PostgreSQL and H2 in PostgreSQL mode.
-- Never edit this file once it has been applied anywhere: add a V2__...sql instead.

create table game_entity (
    id         bigint generated by default as identity primary key,
    -- The id in the API and the URLs; the bigint id never leaves the server.
    public_id  uuid not null unique,
    created_at timestamp with time zone not null
);

-- For the cleanup job, which deletes games created before a cutoff.
create index idx_game_entity_created_at on game_entity (created_at);

create table game_round_entity (
    id           bigint generated by default as identity primary key,
    game_id      bigint not null references game_entity (id) on delete cascade,
    round_number int not null,
    game_type    varchar(64) not null,
    round_key    varchar(255) not null,
    answer_state varchar(32) not null,
    hints_used   int not null,
    wrong_guesses int,
    constraint uq_game_round_number unique (game_id, round_number)
);
