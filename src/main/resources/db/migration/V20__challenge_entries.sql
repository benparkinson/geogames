-- Every challenge gets a table of scores: the creator's, then one per finished game played from the
-- link. The challenge table is dropped and recreated (nobody uses it yet), as the score moves to the
-- entries and a challenge now lives from when it was last played.
drop table challenge;

-- The rounds, mode and difficulty of a finished game, so others can play the same rounds. No user
-- data. Both dates are dates, never timestamps. Deleted once last_used_on is older than
-- geogames.challenges.max-age.
create table challenge (
    id           bigint generated by default as identity primary key,  -- never leaves the server
    public_id    uuid        not null unique,
    game_mode    varchar(64) not null,
    difficulty   varchar(10) not null,  -- EASY, NORMAL or HARD
    rounds       text        not null,  -- JSON: [{"gameType": "TRIPOINT", "roundKey": "..."}, ...]
    max_score    integer     not null,
    created_on   date        not null,
    last_used_on date        not null   -- when a game was last started from it, or it was shared
);

create index challenge_last_used_on on challenge (last_used_on);

-- One finished game's score on a challenge. No link to the game or any player.
create table challenge_entry (
    id           bigint generated by default as identity primary key,  -- the earlier wins a tie
    challenge_id bigint  not null references challenge (id) on delete cascade,
    score        integer not null,
    initials     varchar(3)             -- NULL until entered
);

create index challenge_entry_score on challenge_entry (challenge_id, score);

-- The challenge a game made or was started from, and the game's own entry in it (NULL until the
-- game is finished). Both go with the game after a day.
alter table game_entity add column challenge_id bigint;
alter table game_entity add column challenge_entry_id bigint;
alter table game_entity add constraint fk_game_challenge
    foreign key (challenge_id) references challenge (id) on delete set null;
alter table game_entity add constraint fk_game_challenge_entry
    foreign key (challenge_entry_id) references challenge_entry (id) on delete set null;

create index game_entity_challenge on game_entity (challenge_id);
create index game_entity_challenge_entry on game_entity (challenge_entry_id);
